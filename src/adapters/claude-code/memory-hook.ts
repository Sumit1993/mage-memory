const denyReason = (rel: string): string =>
  `${rel} is regenerated by \`mage index\`; write the memory as its own file under mage/notes/<slug>.md instead (it is listed at the end of the session by \`mage index\`). If a memory write was refused earlier this session, repeat it now as its own file.`;

/** The files `mage index` regenerates at the docs root: INDEX.md, MEMORY.md and _index.<wing>.md. */
function isRegeneratedIndex(rel: string): boolean {
  return rel === INDEX_FILE || rel === MEMORY_FILE || /^_index\..+\.md$/.test(rel);
}

